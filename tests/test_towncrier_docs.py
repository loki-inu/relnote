"""The towncrier alternative page: metadata, wiring, and real commands.

docs/towncrier-alternative.html is a comparison page. The relnote commands
in its shell block are parsed with the real CLI and executed in a scratch
repository. The page's Release body and CHANGELOG.md section must match
that run. GitHub Release commands must use flags already shown on
docs/github-action.html.
"""

from __future__ import annotations

import html
import os
import re
import shlex
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from relnote import __version__
from relnote.__main__ import build_parser
from tests.test_output import _git

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "towncrier-alternative.html"
DOCS = ROOT / "docs"
CANONICAL = "https://loki-inu.github.io/relnote/towncrier-alternative.html"
TITLE = "towncrier alternative without news fragments — relnote"
HASH = re.compile(r"\(`[0-9a-f]{7,}`\)")
DATE = re.compile(r"\] - \d{4}-\d{2}-\d{2}")
GH_FLAG = re.compile(r"--[A-Za-z0-9-]+")


def _blocks() -> list[str]:
    text = PAGE.read_text(encoding="utf-8")
    return [html.unescape(b) for b in re.findall(r"<pre><code>(.*?)</code></pre>", text, re.S)]


def _block(start: str) -> str:
    for block in _blocks():
        if block.startswith(start):
            return block
    raise AssertionError(f"no <pre> block starting with {start!r} in {PAGE.name}")


def _logical_lines(block: str) -> list[str]:
    lines: list[str] = []
    buf = ""
    for raw in block.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.endswith("\\"):
            buf += line[:-1].rstrip() + " "
            continue
        buf += line
        lines.append(buf.strip())
        buf = ""
    if buf.strip():
        lines.append(buf.strip())
    return lines


def _relnote_argv(line: str) -> list[str] | None:
    if line.startswith("python3 -m relnote"):
        rest = line[len("python3 -m relnote"):].strip()
    elif line == "relnote" or line.startswith("relnote "):
        rest = line[len("relnote"):].strip()
    else:
        return None
    return shlex.split(rest)


def _mask(text: str) -> str:
    return DATE.sub("] - DATE", HASH.sub("(`HASH`)", text)).strip()


class TowncrierAlternativePageTests(unittest.TestCase):
    def test_page_exists(self) -> None:
        self.assertTrue(PAGE.is_file(), f"missing {PAGE}")

    def test_canonical_title_and_description(self) -> None:
        text = PAGE.read_text(encoding="utf-8")
        self.assertIn(f"<title>{TITLE}</title>", text)
        self.assertIn(f'<link rel="canonical" href="{CANONICAL}">', text)
        self.assertIn(f'<meta property="og:url" content="{CANONICAL}">', text)
        self.assertIn(f'<meta property="og:title" content="{TITLE}">', text)
        self.assertIn(f'<meta name="twitter:title" content="{TITLE}">', text)
        description = re.search(r'<meta name="description" content="([^"]*)">', text)
        self.assertIsNotNone(description)
        blurb = description.group(1)
        self.assertIn("towncrier", blurb)
        self.assertIn("news fragment", blurb)
        self.assertIn("pyproject.toml", blurb)
        self.assertIn("towncrier.toml", blurb)
        self.assertIn(f'<meta property="og:description" content="{blurb}">', text)
        self.assertIn(f'<meta name="twitter:description" content="{blurb}">', text)
        self.assertIn('"@type": "HowTo"', text)
        self.assertIn('"@type": "FAQPage"', text)
        self.assertIn('"@type": "BreadcrumbList"', text)
        self.assertIn('href="./"', text)
        self.assertIn('href="compare.html"', text)
        lowered = text.lower()
        for banned in (
            "chatgpt",
            "as an ai",
            "language model",
            "written by ai",
            "generated by ai",
            "ai-generated",
        ):
            self.assertNotIn(banned, lowered)
        self.assertIsNone(re.search(r"\bbot\b", lowered))

    def test_linked_from_sitemap_llms_compare_and_index(self) -> None:
        for name in ("sitemap.xml", "llms.txt", "compare.html", "index.html"):
            text = (DOCS / name).read_text(encoding="utf-8")
            self.assertIn("towncrier-alternative.html", text, name)
        sitemap = (DOCS / "sitemap.xml").read_text(encoding="utf-8")
        self.assertIn(f"<loc>{CANONICAL}</loc>", sitemap)

    def test_version_matches_package(self) -> None:
        text = PAGE.read_text(encoding="utf-8")
        self.assertIn(f'"softwareVersion": "{__version__}"', text)
        self.assertIn(f"loki-inu/relnote@v{__version__}", text)
        self.assertIn(f"releases/download/v{__version__}/relnote", text)
        self.assertIn(f"releases/tag/v{__version__}", text)

    def test_commands_are_real(self) -> None:
        blocks = _blocks()
        parser = build_parser()
        saw = False
        for block in blocks:
            for line in _logical_lines(block):
                argv = _relnote_argv(line)
                if argv is None:
                    continue
                saw = True
                if argv[:1] in (["--help"], ["-h"], ["--version"]):
                    continue
                parser.parse_args(argv)
        self.assertTrue(saw, "page shows no relnote command")

        action = (DOCS / "github-action.html").read_text(encoding="utf-8")
        saw_gh = False
        for block in blocks:
            for line in block.splitlines():
                if "gh release" not in line:
                    continue
                saw_gh = True
                flags = GH_FLAG.findall(line)
                self.assertTrue(flags, line)
                for flag in flags:
                    self.assertIn(flag, action, flag)
        self.assertTrue(saw_gh, "page shows no gh release command from the Action guide")

        install = _block("mkdir -p ~/.local/bin")
        self.assertIn(
            f"https://github.com/loki-inu/relnote/releases/download/v{__version__}/relnote",
            install,
        )

        repo = self._repo()
        for line in _logical_lines(_block("python3 -m relnote --next-version")):
            argv = _relnote_argv(line)
            self.assertIsNotNone(argv, line)
            result = self._run(repo, argv or [])
            self.assertEqual(result.returncode, 0, result.stderr + result.stdout)
            if "--next-version" in (argv or []):
                self.assertEqual(result.stdout.strip(), "v1.4.0")
        notes = (repo / "notes.md").read_text(encoding="utf-8")
        self.assertEqual(_mask(notes), _mask(_block("## What's changed")))
        changelog = (repo / "CHANGELOG.md").read_text(encoding="utf-8")
        section = changelog[changelog.index("## [v1.4.0]"):]
        self.assertEqual(_mask(section), _mask(_block("## [v1.4.0]")))
        self.assertIn("compare/v1.3.2...HEAD", notes)
        self.assertIn("compare/v1.3.2...v1.4.0", section)

    def _repo(self) -> Path:
        self._tmp = tempfile.TemporaryDirectory()
        repo = Path(self._tmp.name) / "repo"
        repo.mkdir()
        _git(["init", "--initial-branch=main"], repo)
        _git(["remote", "add", "origin", "https://github.com/you/project.git"], repo)
        _git(["commit", "--allow-empty", "-m", "chore: init"], repo)
        _git(["tag", "v1.3.2"], repo)
        _git(["commit", "--allow-empty", "-m", "feat: add --json output (#12)"], repo)
        _git(["commit", "--allow-empty", "-m", "fix: handle empty config (#13)"], repo)
        self.addCleanup(self._tmp.cleanup)
        return repo

    def _run(self, repo: Path, argv: list[str]) -> subprocess.CompletedProcess[str]:
        env = {
            **os.environ,
            "PYTHONPATH": str(ROOT),
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_CONFIG_GLOBAL": os.devnull,
        }
        for key in ("GIT_AUTHOR_NAME", "GIT_AUTHOR_EMAIL", "GIT_COMMITTER_NAME", "GIT_COMMITTER_EMAIL"):
            env.pop(key, None)
        return subprocess.run(
            [sys.executable, "-m", "relnote", *argv],
            cwd=repo,
            env=env,
            capture_output=True,
            text=True,
        )


if __name__ == "__main__":
    unittest.main()

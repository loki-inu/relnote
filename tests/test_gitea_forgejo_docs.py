"""The Gitea / Forgejo page, checked against the CLI.

Builds the history on docs/gitea-forgejo.html, runs the relnote commands,
and checks that a Codeberg or Gitea origin omits the GitHub compare link
and the changelog pull-request link. Also checks the releases API snippet
and the links from the sitemap, llms.txt, the index, and the CI pages.
"""

from __future__ import annotations

import html
import json
import os
import re
import shlex
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from relnote import __version__
from relnote.__main__ import build_parser
from tests.test_output import _git

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "gitea-forgejo.html"
DOCS = ROOT / "docs"
CANONICAL = "https://loki-inu.github.io/relnote/gitea-forgejo.html"
TITLE = "Release notes for Gitea and Forgejo — relnote"
HASH = re.compile(r"\(`[0-9a-f]{7,}`\)")
DESCRIPTION = (
    "Write release notes for a Gitea or Forgejo project, including "
    "Codeberg, from conventional commits. Generate them locally or in "
    "Gitea Actions or Forgejo Actions, then paste the file or publish it "
    "with the releases API or tea. A GitHub compare link is added only "
    "when origin is github.com."
)
JSON_LINE = (
    "python3 -c 'import json, os, pathlib; "
    'pathlib.Path("release.json").write_text(json.dumps({"tag_name": os.environ["TAG"], '
    '"target_commitish": os.environ["TAG"], "name": os.environ["TAG"], '
    '"body": pathlib.Path("notes.md").read_text(encoding="utf-8"), "draft": True}), '
    "encoding=\"utf-8\")'"
)


def _blocks() -> list[str]:
    text = PAGE.read_text(encoding="utf-8")
    return [html.unescape(b) for b in re.findall(r"<pre><code>(.*?)</code></pre>", text, re.S)]


def _containing(*snippets: str) -> str:
    matches = [block for block in _blocks() if all(snippet in block for snippet in snippets)]
    if len(matches) != 1:
        raise AssertionError(f"{len(matches)} <pre> blocks contain {snippets!r}")
    return matches[0]


def _mask(text: str) -> str:
    return HASH.sub("(`HASH`)", text).strip()


def _relnote_lines() -> list[str]:
    lines: list[str] = []
    for block in _blocks():
        for raw in block.splitlines():
            line = raw.strip()
            if line == "python3 -m relnote" or line.startswith("python3 -m relnote "):
                lines.append(line)
    return lines


class GiteaForgejoPageStaticTests(unittest.TestCase):
    def test_page_exists(self) -> None:
        self.assertTrue(PAGE.is_file(), f"missing {PAGE}")

    def test_canonical_title_and_description(self) -> None:
        text = PAGE.read_text(encoding="utf-8")
        self.assertIn(f"<title>{TITLE}</title>", text)
        self.assertIn(f'<link rel="canonical" href="{CANONICAL}">', text)
        self.assertIn(f'<meta property="og:url" content="{CANONICAL}">', text)
        self.assertIn(f'<meta property="og:title" content="{TITLE}">', text)
        self.assertIn(f'<meta name="twitter:title" content="{TITLE}">', text)
        self.assertIn(f'<meta name="description" content="{DESCRIPTION}">', text)
        self.assertIn(f'<meta property="og:description" content="{DESCRIPTION}">', text)
        self.assertIn(f'<meta name="twitter:description" content="{DESCRIPTION}">', text)
        self.assertIn('"@type": "HowTo"', text)
        self.assertIn('"@type": "FAQPage"', text)
        self.assertIn('"@type": "BreadcrumbList"', text)
        self.assertIn('href="./"', text)
        self.assertIn(f'"softwareVersion": "{__version__}"', text)
        self.assertIn("codeberg.org", text)
        self.assertIn("Authorization: token", text)
        self.assertIn("$API/repos/$REPO/releases", text)
        lowered = text.lower()
        for banned in (
            "chatgpt",
            "as an ai",
            "language model",
            "written by ai",
            "generated by ai",
            "ai-generated",
        ):
            self.assertNotIn(banned, lowered)
        self.assertIsNone(re.search(r"\bbot\b", lowered))

    def test_linked_from_sitemap_llms_index_and_ci_pages(self) -> None:
        for name in (
            "sitemap.xml",
            "llms.txt",
            "index.html",
            "ci.html",
            "compare.html",
            "github-action.html",
        ):
            text = (DOCS / name).read_text(encoding="utf-8")
            self.assertIn("gitea-forgejo.html", text, name)
        sitemap = (DOCS / "sitemap.xml").read_text(encoding="utf-8")
        self.assertIn(f"<loc>{CANONICAL}</loc>", sitemap)
        readme = (ROOT / "README.md").read_text(encoding="utf-8")
        self.assertIn("gitea-forgejo.html", readme)
        llms = (DOCS / "llms.txt").read_text(encoding="utf-8")
        self.assertIn(CANONICAL, llms)
        section = llms.lower()
        start = section.find("## gitea and forgejo")
        end = section.find("## standard-version")
        self.assertGreater(start, 0)
        self.assertGreater(end, start)
        self.assertIsNone(re.search(r"\bbot\b", section[start:end]))

    def test_version_matches_package(self) -> None:
        text = PAGE.read_text(encoding="utf-8")
        self.assertIn(f"releases/download/v{__version__}/relnote", text)
        self.assertNotIn("loki-inu/relnote@v0.3.8", text)
        self.assertEqual(__version__, "0.3.7")

    def test_commands_match_the_cli(self) -> None:
        parser = build_parser()
        lines = _relnote_lines()
        self.assertIn("python3 -m relnote --next-version", lines)
        self.assertIn("python3 -m relnote", lines)
        self.assertIn("python3 -m relnote --since v1.2.0 --until v1.3.0", lines)
        self.assertIn("python3 -m relnote --output notes.md --quiet", lines)
        self.assertIn(
            "python3 -m relnote --since v1.2.0 --until v1.3.0 "
            "--changelog CHANGELOG.md --changelog-title v1.3.0 --date 2026-11-26 --quiet",
            lines,
        )
        saw = False
        for line in lines:
            argv = shlex.split(line[len("python3 -m relnote"):].strip())
            parser.parse_args(argv)
            saw = True
        self.assertTrue(saw, "page shows no relnote command")

    def test_workflows_match_documented_gitea_and_forgejo_syntax(self) -> None:
        gitea = _containing("on: [push]", "secrets.GITEA_TOKEN")
        forgejo = _containing("secrets.FORGEJO_TOKEN", "data.forgejo.org")
        for block in (gitea, forgejo):
            self.assertIn("fetch-depth: 0", block)
            self.assertIn(f"releases/download/v{__version__}/relnote", block)
            self.assertIn("./relnote --no-bots --output notes.md --quiet", block)
            self.assertIn(JSON_LINE, block)
            self.assertIn("Authorization: token $TOKEN", block)
            self.assertIn('"$API/repos/$REPO/releases"', block)
            self.assertNotIn("uses: loki-inu/relnote", block)
        self.assertIn("uses: actions/checkout@v4", gitea)
        self.assertIn("permissions:", gitea)
        self.assertIn("contents: read", gitea)
        self.assertIn("releases: write", gitea)
        self.assertIn('REF_TYPE: ${{ gitea.ref_type }}', gitea)
        self.assertIn(".gitea/workflows/release-notes.yaml", PAGE.read_text(encoding="utf-8"))
        self.assertIn("uses: https://data.forgejo.org/actions/checkout@v7", forgejo)
        self.assertIn("tags:", forgejo)
        self.assertIn("runs-on: docker", forgejo)
        self.assertIn(".forgejo/workflows/release-notes.yaml", PAGE.read_text(encoding="utf-8"))
        tea = _containing("tea releases create")
        self.assertIn("--note-file notes.md", tea)
        self.assertIn("--draft", tea)
        self.assertIn("--tag v1.3.0", tea)
        self.assertIn("--repo you/demo", tea)

    def test_release_json_snippet_embeds_the_notes(self) -> None:
        found = [
            line.strip()
            for block in _blocks()
            for line in block.splitlines()
            if line.strip().startswith("python3 -c ")
        ]
        self.assertGreaterEqual(len(found), 2)
        self.assertTrue(all(line == JSON_LINE for line in found))
        code = JSON_LINE[len("python3 -c "):]
        self.assertTrue(code.startswith("'") and code.endswith("'"))
        script = code[1:-1]
        with tempfile.TemporaryDirectory() as tmp:
            notes = Path(tmp) / "notes.md"
            expected = "## What's changed\n\n- quotes \" and `ticks`\n"
            notes.write_text(expected, encoding="utf-8")
            env = {**os.environ, "TAG": "v1.3.0"}
            result = subprocess.run(
                [sys.executable, "-c", script],
                cwd=tmp,
                env=env,
                capture_output=True,
                text=True,
                check=False,
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            payload = json.loads((Path(tmp) / "release.json").read_text(encoding="utf-8"))
        self.assertEqual(payload["tag_name"], "v1.3.0")
        self.assertEqual(payload["target_commitish"], "v1.3.0")
        self.assertEqual(payload["name"], "v1.3.0")
        self.assertTrue(payload["draft"])
        self.assertEqual(payload["body"], expected)


class GiteaForgejoPageTests(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        base = Path(self._tmp.name)
        self.repo = base / "repo"
        self.repo.mkdir()
        self.gitconfig = base / "gitconfig"
        self.gitconfig.write_text("", encoding="utf-8")
        _git(["init", "--initial-branch=main"], self.repo)
        _git(["remote", "add", "origin", "https://codeberg.org/you/demo.git"], self.repo)
        (self.repo / "README").write_text("demo\n", encoding="utf-8")
        _git(["add", "README"], self.repo)
        _git(["commit", "-m", "feat: first release"], self.repo)
        _git(["tag", "-a", "v1.2.0", "-m", "v1.2.0"], self.repo)
        history = _containing("git log --oneline").splitlines()[1:]
        for subject in reversed(history):
            _git(["commit", "--allow-empty", "-m", subject], self.repo)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def _env(self) -> dict[str, str]:
        return {
            **os.environ,
            "PYTHONPATH": str(ROOT),
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_CONFIG_GLOBAL": str(self.gitconfig),
            "GIT_AUTHOR_NAME": "Ada Lovelace",
            "GIT_AUTHOR_EMAIL": "ada@example.com",
            "GIT_COMMITTER_NAME": "Ada Lovelace",
            "GIT_COMMITTER_EMAIL": "ada@example.com",
        }

    def _run(self, *argv: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, "-m", "relnote", *argv],
            cwd=self.repo,
            env=self._env(),
            capture_output=True,
            text=True,
            check=False,
        )

    def _origin(self, url: str) -> None:
        _git(["remote", "set-url", "origin", url], self.repo)

    def test_forge_origin_has_no_github_compare_link(self) -> None:
        nxt = self._run("--next-version")
        self.assertEqual(nxt.returncode, 0, nxt.stderr)
        self.assertEqual(nxt.stdout.strip(), "v1.3.0")
        self.assertIn("v1.3.0", [block.strip() for block in _blocks()])

        _git(["tag", "-a", "v1.3.0", "-m", "v1.3.0"], self.repo)
        forge_notes = [
            block for block in _blocks()
            if "Range: `v1.2.0` → `v1.3.0`." in block
            and "(#41)" in block
            and "Full changelog" not in block
        ]
        self.assertEqual(len(forge_notes), 1, [block[:40] for block in forge_notes])
        notes = forge_notes[0]
        self.assertNotIn("github.com", notes)
        plain = self._run()
        self.assertEqual(plain.returncode, 0, plain.stderr)
        self.assertEqual(_mask(plain.stdout), _mask(notes))
        self.assertNotIn("Full changelog", plain.stdout)

        ranged = self._run("--since", "v1.2.0", "--until", "v1.3.0")
        self.assertEqual(ranged.returncode, 0, ranged.stderr)
        self.assertEqual(_mask(ranged.stdout), _mask(notes))

        quiet = self._run("--output", "notes.md", "--quiet")
        self.assertEqual(quiet.returncode, 0, quiet.stderr)
        self.assertEqual(quiet.stdout, "")
        written = (self.repo / "notes.md").read_text(encoding="utf-8")
        self.assertEqual(_mask(written), _mask(notes))
        self.assertIn("(#41)", written)
        self.assertNotIn("](https://github.com/", written)

        for url in (
            "https://gitea.com/you/demo.git",
            "git@codeberg.org:you/demo.git",
            "https://git.example.com/you/demo.git",
        ):
            self._origin(url)
            again = self._run("--since", "v1.2.0", "--until", "v1.3.0")
            self.assertEqual(again.returncode, 0, again.stderr)
            self.assertEqual(_mask(again.stdout), _mask(notes), url)
            self.assertNotIn("Full changelog", again.stdout, url)

    def test_github_origin_adds_the_compare_link(self) -> None:
        _git(["tag", "-a", "v1.3.0", "-m", "v1.3.0"], self.repo)
        self._origin("https://github.com/you/demo.git")
        ranged = self._run("--since", "v1.2.0", "--until", "v1.3.0")
        self.assertEqual(ranged.returncode, 0, ranged.stderr)
        github_notes = _containing(
            "## What's changed",
            "**Full changelog:** https://github.com/you/demo/compare/",
        )
        self.assertEqual(_mask(ranged.stdout), _mask(github_notes))
        self.assertIn(
            "**Full changelog:** https://github.com/you/demo/compare/v1.2.0...v1.3.0",
            ranged.stdout,
        )
        self.assertIn("(#41)", ranged.stdout)
        self.assertNotIn("](https://github.com/", ranged.stdout)

    def test_changelog_links_pull_requests_only_for_github(self) -> None:
        _git(["tag", "-a", "v1.3.0", "-m", "v1.3.0"], self.repo)
        codeberg = self._run(
            "--since", "v1.2.0", "--until", "v1.3.0",
            "--changelog", "CHANGELOG.md",
            "--changelog-title", "v1.3.0",
            "--date", "2026-11-26",
            "--quiet",
        )
        self.assertEqual(codeberg.returncode, 0, codeberg.stderr)
        self.assertEqual(codeberg.stdout, "")
        written = (self.repo / "CHANGELOG.md").read_text(encoding="utf-8")
        sample = _containing("# Changelog", "add paging (#41)")
        self.assertEqual(_mask(written), _mask(sample))
        self.assertNotIn("github.com", written)

        self._origin("https://github.com/you/demo.git")
        (self.repo / "CHANGELOG.md").unlink()
        github = self._run(
            "--since", "v1.2.0", "--until", "v1.3.0",
            "--changelog", "CHANGELOG.md",
            "--changelog-title", "v1.3.0",
            "--date", "2026-11-26",
            "--quiet",
        )
        self.assertEqual(github.returncode, 0, github.stderr)
        linked = (self.repo / "CHANGELOG.md").read_text(encoding="utf-8")
        sample = _containing("https://github.com/you/demo/pull/41")
        self.assertEqual(_mask(linked), _mask(sample))
        self.assertIn(
            "([#41](https://github.com/you/demo/pull/41))",
            linked,
        )


if __name__ == "__main__":
    unittest.main()

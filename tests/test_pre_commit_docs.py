"""The pre-commit / git hook page, checked against the CLI.

Builds the histories shown on docs/pre-commit.html, runs the relnote
commands and the pre-push scripts, and checks exit statuses. Also checks
that .pre-commit-hooks.yaml matches the page and that the page is linked
from the sitemap, llms.txt, the index, and the other how-to pages.
"""

from __future__ import annotations

import contextlib
import html
import io
import os
import re
import shlex
import stat
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from relnote import __version__
from relnote.__main__ import build_parser
from tests.test_output import _git

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "pre-commit.html"
DOCS = ROOT / "docs"
HOOK = ROOT / ".pre-commit-hooks.yaml"
CANONICAL = "https://loki-inu.github.io/relnote/pre-commit.html"
TITLE = "Release notes with pre-commit / git hooks — relnote"
HASH = re.compile(r"\(`[0-9a-f]{7,}`\)")
DESCRIPTION = (
    "Print or check GitHub release notes from a pre-push hook or the "
    "pre-commit framework. relnote reads commits already in the repository, "
    "from the latest tag to HEAD. Exit 0 writes the notes, exit 1 is an "
    "empty range or a bad ref, and exit 2 is a bad --quiet or an extra "
    "argument. There is no --check flag."
)


def _blocks() -> list[str]:
    text = PAGE.read_text(encoding="utf-8")
    return [html.unescape(b) for b in re.findall(r"<pre><code>(.*?)</code></pre>", text, re.S)]


def _containing(*snippets: str) -> str:
    matches = [block for block in _blocks() if all(snippet in block for snippet in snippets)]
    if len(matches) != 1:
        raise AssertionError(f"{len(matches)} <pre> blocks contain {snippets!r}")
    return matches[0]


def _mask(text: str) -> str:
    return HASH.sub("(`HASH`)", text).strip()


def _relnote_lines() -> list[str]:
    lines: list[str] = []
    for block in _blocks():
        for raw in block.splitlines():
            line = raw.strip()
            if line == "python3 -m relnote" or line.startswith("python3 -m relnote "):
                lines.append(line)
    return lines


class PreCommitPageStaticTests(unittest.TestCase):
    def test_page_exists(self) -> None:
        self.assertTrue(PAGE.is_file(), f"missing {PAGE}")
        self.assertTrue(HOOK.is_file(), f"missing {HOOK}")

    def test_canonical_title_and_description(self) -> None:
        text = PAGE.read_text(encoding="utf-8")
        self.assertIn(f"<title>{TITLE}</title>", text)
        self.assertIn(f'<link rel="canonical" href="{CANONICAL}">', text)
        self.assertIn(f'<meta property="og:url" content="{CANONICAL}">', text)
        self.assertIn(f'<meta property="og:title" content="{TITLE}">', text)
        self.assertIn(f'<meta name="twitter:title" content="{TITLE}">', text)
        self.assertIn(f'<meta name="description" content="{DESCRIPTION}">', text)
        self.assertIn(f'<meta property="og:description" content="{DESCRIPTION}">', text)
        self.assertIn(f'<meta name="twitter:description" content="{DESCRIPTION}">', text)
        self.assertIn('"@type": "HowTo"', text)
        self.assertIn('"@type": "FAQPage"', text)
        self.assertIn('"@type": "BreadcrumbList"', text)
        self.assertIn('href="./"', text)
        self.assertIn(f'"softwareVersion": "{__version__}"', text)
        self.assertIn("pass_filenames: false", text)
        self.assertIn("always_run: true", text)
        self.assertIn("The v0.3.7 tag does not contain that file.", text)
        self.assertIn("rev: v0.3.8", text)
        self.assertNotIn("rev: v0.3.7", text)
        lowered = text.lower()
        for banned in (
            "chatgpt",
            "as an ai",
            "language model",
            "written by ai",
            "generated by ai",
            "ai-generated",
        ):
            self.assertNotIn(banned, lowered)
        self.assertIsNone(re.search(r"\bbot\b", lowered))

    def test_linked_from_sitemap_llms_index_and_howto_pages(self) -> None:
        for name in (
            "sitemap.xml",
            "llms.txt",
            "index.html",
            "ci.html",
            "github-action.html",
            "windows.html",
            "changelog.html",
        ):
            text = (DOCS / name).read_text(encoding="utf-8")
            self.assertIn("pre-commit.html", text, name)
        sitemap = (DOCS / "sitemap.xml").read_text(encoding="utf-8")
        self.assertIn(f"<loc>{CANONICAL}</loc>", sitemap)
        readme = (ROOT / "README.md").read_text(encoding="utf-8")
        self.assertIn("pre-commit.html", readme)
        llms = (DOCS / "llms.txt").read_text(encoding="utf-8").lower()
        self.assertIsNone(re.search(r"\bbot\b", llms[llms.find("## pre-commit"):llms.find("## gitlab")]))

    def test_hook_manifest_matches_the_page_and_the_console_script(self) -> None:
        manifest = HOOK.read_text(encoding="utf-8")
        self.assertEqual(manifest.strip(), _containing("language: python").strip())
        for key in (
            "id: relnote\n",
            "entry: relnote\n",
            "language: python\n",
            "always_run: true\n",
            "pass_filenames: false\n",
            "stages: [pre-push, manual]\n",
            "verbose: true\n",
            'minimum_pre_commit_version: "3.2.0"\n',
        ):
            self.assertIn(key, manifest)
        project = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
        self.assertIn('relnote = "relnote.__main__:main"', project)
        self.assertIsNone(re.search(r"\bbot\b", manifest.lower()))

    def test_commands_match_the_cli(self) -> None:
        parser = build_parser()
        lines = _relnote_lines()
        self.assertIn("python3 -m relnote", lines)
        self.assertIn("python3 -m relnote --output notes.md --quiet", lines)
        self.assertIn("python3 -m relnote --include-release-commits", lines)
        self.assertIn("python3 -m relnote README", lines)
        saw = False
        for line in lines:
            argv = shlex.split(line[len("python3 -m relnote"):].strip())
            if argv == ["README"]:
                with contextlib.redirect_stderr(io.StringIO()):
                    with self.assertRaises(SystemExit) as caught:
                        parser.parse_args(argv)
                self.assertEqual(caught.exception.code, 2)
                continue
            parser.parse_args(argv)
            saw = True
        self.assertTrue(saw, "page shows no relnote command")
        help_text = subprocess.run(
            [sys.executable, "-m", "relnote", "--help"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertEqual(help_text.returncode, 0, help_text.stderr)
        self.assertNotIn("--check", help_text.stdout)
        self.assertNotIn("--dry-run", help_text.stdout)

    def test_local_hook_configs_do_not_pass_filenames(self) -> None:
        check = _containing("repo: local", "id: relnote\n")
        preview = _containing("ignore-exit-code")
        for block in (check, preview):
            self.assertIn("pass_filenames: false", block)
            self.assertIn("always_run: true", block)
            self.assertIn("stages: [pre-push, manual]", block)
            self.assertIn("verbose: true", block)
        self.assertIn("entry: relnote\n", check)
        self.assertIn("entry: pre-commit hazmat ignore-exit-code relnote\n", preview)
        self.assertNotIn("relnote --", preview)
        self.assertIn('minimum_pre_commit_version: "4.5.0"', preview)


class PreCommitPageTests(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        base = Path(self._tmp.name)
        self.repo = base / "repo"
        self.repo.mkdir()
        self.gitconfig = base / "gitconfig"
        self.gitconfig.write_text("", encoding="utf-8")
        bindir = base / "bin"
        bindir.mkdir()
        shim = bindir / "relnote"
        shim.write_text(
            "#!/bin/sh\nexec python3 -m relnote \"$@\"\n",
            encoding="utf-8",
            newline="\n",
        )
        shim.chmod(0o755)
        self._path = str(bindir) + os.pathsep + os.environ.get("PATH", "")
        _git(["init", "--initial-branch=main"], self.repo)
        _git(["remote", "add", "origin", "https://github.com/you/demo.git"], self.repo)
        (self.repo / "README").write_text("hello\n", encoding="utf-8")
        _git(["add", "README"], self.repo)
        _git(["commit", "-m", "feat: add readme"], self.repo)
        _git(["tag", "-a", "v1.2.0", "-m", "v1.2.0"], self.repo)
        history = _containing("feat(api): add a context").splitlines()[1:]
        for subject in reversed(history):
            _git(["commit", "--allow-empty", "-m", subject], self.repo)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def _env(self) -> dict[str, str]:
        return {
            **os.environ,
            "PATH": self._path,
            "PYTHONPATH": str(ROOT),
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_CONFIG_GLOBAL": str(self.gitconfig),
            "GIT_AUTHOR_NAME": "Ada Lovelace",
            "GIT_AUTHOR_EMAIL": "ada@example.com",
            "GIT_COMMITTER_NAME": "Ada Lovelace",
            "GIT_COMMITTER_EMAIL": "ada@example.com",
        }

    def _run(self, *argv: str, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, "-m", "relnote", *argv],
            cwd=cwd or self.repo,
            env=self._env(),
            capture_output=True,
            text=True,
            check=False,
        )

    def _empty_repo(self, name: str = "empty") -> Path:
        repo = Path(self._tmp.name) / name
        repo.mkdir()
        _git(["init", "--initial-branch=main"], repo)
        _git(["remote", "add", "origin", "https://github.com/you/demo.git"], repo)
        (repo / "README").write_text("hello\n", encoding="utf-8")
        _git(["add", "README"], repo)
        _git(["commit", "-m", "feat: add readme"], repo)
        _git(["tag", "-a", "v1.2.0", "-m", "v1.2.0"], repo)
        history = _containing("chore(release): v1.3.0").splitlines()[1:]
        for subject in reversed(history):
            _git(["commit", "--allow-empty", "-m", subject], repo)
        return repo

    def _hook(self, snippet: str) -> str:
        return _containing(snippet)

    def test_notes_match_the_page(self) -> None:
        plain = self._run()
        self.assertEqual(plain.returncode, 0, plain.stderr)
        notes = _containing("add a context to Client.Do", "Range: `v1.2.0` → `HEAD`.")
        self.assertEqual(_mask(plain.stdout), _mask(notes))
        self.assertIn("compare/v1.2.0...HEAD", plain.stdout)

        quiet = self._run("--output", "notes.md", "--quiet")
        self.assertEqual(quiet.returncode, 0, quiet.stderr)
        self.assertEqual(quiet.stdout, "")
        written = (self.repo / "notes.md").read_text(encoding="utf-8")
        self.assertEqual(_mask(written), _mask(notes))

        _git(["tag", "-a", "v1.3.0", "-m", "v1.3.0"], self.repo)
        tagged = self._run()
        self.assertEqual(tagged.returncode, 0, tagged.stderr)
        tagged_notes = _containing("Range: `v1.2.0` → `v1.3.0`.")
        self.assertEqual(_mask(tagged.stdout), _mask(tagged_notes))
        self.assertIn("compare/v1.2.0...v1.3.0", tagged.stdout)

    def test_status_messages_match_the_page(self) -> None:
        page = PAGE.read_text(encoding="utf-8")
        cases = [
            (["--quiet"], 2, "relnote: --quiet requires --output or --changelog"),
            (["README"], 2, "unrecognized arguments: README"),
            (["--since", "no-such-tag"], 1, "relnote: unknown ref: no-such-tag"),
            (["--since", "HEAD"], 1, "relnote: no commits in range HEAD..HEAD"),
            (["--max", "0"], 1, "relnote: --max must be >= 1"),
            (["--date", "yesterday", "--changelog", "CHANGELOG.md"], 1, "relnote: --date must look like YYYY-MM-DD"),
            (["--output", "missing-dir/notes.md"], 1, "relnote: output directory does not exist"),
        ]
        for argv, code, message in cases:
            result = self._run(*argv)
            self.assertEqual(result.returncode, code, (argv, result.stderr))
            self.assertIn(message, result.stderr)
            self.assertIn(html.escape(message).replace("&#x27;", "'"), page.replace("&#x27;", "'"))
            self.assertIn(message, html.unescape(page))

        nowhere = Path(self._tmp.name) / "not-a-repo"
        nowhere.mkdir()
        missing = self._run(cwd=nowhere)
        self.assertEqual(missing.returncode, 1, missing.stderr)
        self.assertIn("relnote: not a git repository (or any parent)", missing.stderr)
        self.assertIn("relnote: not a git repository (or any parent)", html.unescape(page))

        first = self._run("--changelog", "CHANGELOG.md", "--date", "2026-11-25", "--quiet")
        self.assertEqual(first.returncode, 0, first.stderr)
        before = (self.repo / "CHANGELOG.md").read_text(encoding="utf-8")
        again = self._run("--changelog", "CHANGELOG.md", "--date", "2026-11-25", "--quiet")
        self.assertEqual(again.returncode, 1, again.stderr)
        self.assertIn("relnote: changelog already has a section for", again.stderr)
        self.assertIn("changelog already has a section for", html.unescape(page))
        self.assertEqual((self.repo / "CHANGELOG.md").read_text(encoding="utf-8"), before)

        bad = Path(self._tmp.name) / "bad-tag"
        bad.mkdir()
        _git(["init", "--initial-branch=main"], bad)
        _git(["commit", "--allow-empty", "-m", "feat: first"], bad)
        _git(["tag", "-a", "not-semver", "-m", "not-semver"], bad)
        _git(["commit", "--allow-empty", "-m", "fix: second"], bad)
        version = self._run("--next-version", cwd=bad)
        self.assertEqual(version.returncode, 1, version.stderr)
        self.assertIn(
            "relnote: tag 'not-semver' is not a semantic version (x.y.z)",
            version.stderr,
        )
        self.assertIn("is not a semantic version (x.y.z)", html.unescape(page))

    def test_release_commit_only_exits_1_until_included(self) -> None:
        repo = self._empty_repo()
        empty = self._run(cwd=repo)
        self.assertEqual(empty.returncode, 1, empty.stderr)
        self.assertEqual(empty.stdout, "")
        self.assertEqual(
            empty.stderr.strip(),
            _containing("relnote: no commits in range v1.2.0..HEAD").strip(),
        )
        kept = self._run("--include-release-commits", cwd=repo)
        self.assertEqual(kept.returncode, 0, kept.stderr)
        sample = _containing("**release:**")
        self.assertEqual(_mask(kept.stdout), _mask(sample))

    def _run_hook(self, script: str, cwd: Path) -> subprocess.CompletedProcess[str]:
        path = cwd / "hook.sh"
        path.write_text(script if script.endswith("\n") else script + "\n", encoding="utf-8", newline="\n")
        path.chmod(path.stat().st_mode | stat.S_IEXEC)
        return subprocess.run(
            ["sh", str(path)],
            cwd=cwd,
            env=self._env(),
            capture_output=True,
            text=True,
            check=False,
        )

    def test_preview_hook_exits_0_and_check_hook_propagates(self) -> None:
        preview = self._hook("exit 0")
        check = self._hook("exec relnote")
        self.assertTrue(preview.startswith("#!/bin/sh"))
        self.assertTrue(check.startswith("#!/bin/sh"))

        shown = self._run_hook(preview, self.repo)
        self.assertEqual(shown.returncode, 0, shown.stderr)
        self.assertIn("What's changed", shown.stdout)

        blocked = self._run_hook(check, self._empty_repo("empty-check"))
        self.assertEqual(blocked.returncode, 1, blocked.stderr)
        self.assertIn("relnote: no commits in range v1.2.0..HEAD", blocked.stderr)

        allowed = self._run_hook(preview, self._empty_repo("empty-preview"))
        self.assertEqual(allowed.returncode, 0, allowed.stderr)
        self.assertIn("relnote: no commits in range v1.2.0..HEAD", allowed.stderr)
        self.assertEqual(allowed.stdout, "")

    def test_check_hook_blocks_git_push_when_the_range_is_empty(self) -> None:
        def push(repo: Path, script: str) -> subprocess.CompletedProcess[str]:
            bare = repo.parent / f"{repo.name}-bare.git"
            subprocess.run(
                ["git", "init", "--bare", "--initial-branch=main", str(bare)],
                check=True,
                capture_output=True,
                text=True,
            )
            _git(["remote", "add", "localbare", str(bare)], repo)
            hook = repo / ".git" / "hooks" / "pre-push"
            hook.write_text(script if script.endswith("\n") else script + "\n", encoding="utf-8", newline="\n")
            hook.chmod(0o755)
            return subprocess.run(
                ["git", "push", "localbare", "HEAD:main"],
                cwd=repo,
                env=self._env(),
                capture_output=True,
                text=True,
                check=False,
                timeout=30,
            )

        ok = push(self.repo, self._hook("exec relnote"))
        self.assertEqual(ok.returncode, 0, ok.stderr + ok.stdout)
        self.assertIn("What's changed", ok.stdout)

        empty = self._empty_repo("empty-push")
        blocked = push(empty, self._hook("exec relnote"))
        self.assertNotEqual(blocked.returncode, 0)
        self.assertIn("relnote: no commits in range v1.2.0..HEAD", blocked.stderr)
        # The rejected push did not create the branch on the remote.
        remote = subprocess.run(
            ["git", "--git-dir", str(empty.parent / "empty-push-bare.git"), "rev-parse", "main"],
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertNotEqual(remote.returncode, 0)

        preview = push(self._empty_repo("empty-preview-push"), self._hook("exit 0"))
        self.assertEqual(preview.returncode, 0, preview.stderr + preview.stdout)



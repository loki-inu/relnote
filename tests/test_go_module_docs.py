"""The Go module walkthrough on docs/go-module.html, run for real.

Builds the page's go.mod and history in a scratch repository, runs the
relnote commands shown on the page, and compares --next-version, the
tagged range, the no-flag tag-push range, and --output notes.md with the
page. Checks sitemap, llms.txt, and the links from the other ecosystem
pages.
"""

from __future__ import annotations

import html
import os
import re
import shlex
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from relnote import __version__
from relnote.__main__ import build_parser
from tests.test_output import _git

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "go-module.html"
DOCS = ROOT / "docs"
CANONICAL = "https://loki-inu.github.io/relnote/go-module.html"
TITLE = "Release notes for a Go module from git tags — relnote"
HASH = re.compile(r"\(`[0-9a-f]{7,}`\)")
DESCRIPTION = (
    "Write GitHub release notes for a Go module from conventional commits "
    "between two tags (v1.2.0..v1.3.0). A tag-push workflow uses the "
    "loki-inu/relnote action for the Release body. For v2 and later, the "
    "module path in go.mod ends in /vN. GoReleaser takes the same file with "
    "--release-notes."
)


def _blocks() -> list[str]:
    text = PAGE.read_text(encoding="utf-8")
    return [html.unescape(b) for b in re.findall(r"<pre><code>(.*?)</code></pre>", text, re.S)]


def _block(start: str) -> str:
    for block in _blocks():
        if block.startswith(start):
            return block
    raise AssertionError(f"no <pre> block starting with {start!r} in {PAGE.name}")


def _exact(text: str) -> str:
    for block in _blocks():
        if block.strip() == text:
            return block.strip()
    raise AssertionError(f"no <pre> block equal to {text!r} in {PAGE.name}")


def _mask(text: str) -> str:
    return HASH.sub("(`HASH`)", text).strip()


def _relnote_lines() -> list[str]:
    lines: list[str] = []
    for block in _blocks():
        for raw in block.splitlines():
            line = raw.strip()
            if line == "python3 -m relnote" or line.startswith("python3 -m relnote "):
                lines.append(line)
    return lines


class GoModulePageStaticTests(unittest.TestCase):
    def test_page_exists(self) -> None:
        self.assertTrue(PAGE.is_file(), f"missing {PAGE}")

    def test_canonical_title_and_description(self) -> None:
        text = PAGE.read_text(encoding="utf-8")
        self.assertIn(f"<title>{TITLE}</title>", text)
        self.assertIn(f'<link rel="canonical" href="{CANONICAL}">', text)
        self.assertIn(f'<meta property="og:url" content="{CANONICAL}">', text)
        self.assertIn(f'<meta property="og:title" content="{TITLE}">', text)
        self.assertIn(f'<meta name="twitter:title" content="{TITLE}">', text)
        self.assertIn(f'<meta name="description" content="{DESCRIPTION}">', text)
        self.assertIn(f'<meta property="og:description" content="{DESCRIPTION}">', text)
        self.assertIn(f'<meta name="twitter:description" content="{DESCRIPTION}">', text)
        self.assertIn('"@type": "HowTo"', text)
        self.assertIn('"@type": "FAQPage"', text)
        self.assertIn('"@type": "BreadcrumbList"', text)
        self.assertIn('href="./"', text)
        self.assertIn("module github.com/you/demo/v2", text)
        self.assertIn("v2/v2.0.0", text)
        lowered = text.lower()
        for banned in (
            "chatgpt",
            "as an ai",
            "language model",
            "written by ai",
            "generated by ai",
            "ai-generated",
        ):
            self.assertNotIn(banned, lowered)
        self.assertIsNone(re.search(r"\bbot\b", lowered))

    def test_linked_from_sitemap_llms_index_and_ecosystem_pages(self) -> None:
        for name in (
            "sitemap.xml",
            "llms.txt",
            "index.html",
            "npm-package.html",
            "python-package.html",
            "rust-crate.html",
        ):
            text = (DOCS / name).read_text(encoding="utf-8")
            self.assertIn("go-module.html", text, name)
        sitemap = (DOCS / "sitemap.xml").read_text(encoding="utf-8")
        self.assertIn(f"<loc>{CANONICAL}</loc>", sitemap)
        readme = (ROOT / "README.md").read_text(encoding="utf-8")
        self.assertIn("go-module.html", readme)

    def test_version_matches_package(self) -> None:
        text = PAGE.read_text(encoding="utf-8")
        self.assertIn(f"loki-inu/relnote@v{__version__}", text)
        self.assertNotIn("loki-inu/relnote@v0.3.9", text)

    def test_commands_match_the_cli_and_action(self) -> None:
        parser = build_parser()
        lines = _relnote_lines()
        self.assertIn("python3 -m relnote --next-version", lines)
        self.assertIn("python3 -m relnote --since v1.2.0 --until v1.3.0", lines)
        self.assertIn("python3 -m relnote", lines)
        saw = False
        for line in lines:
            argv = shlex.split(line[len("python3 -m relnote"):].strip())
            if argv[:1] in (["--help"], ["-h"], ["--version"]):
                continue
            parser.parse_args(argv)
            saw = True
        self.assertTrue(saw, "page shows no relnote command")

        action = (ROOT / "action.yml").read_text(encoding="utf-8")
        for name in ("since:", "until:", "no-bots:", "path:", "tag-prefix:", "notes:"):
            self.assertIn(name, action, name)
        workflow = _block("name: Release")
        self.assertIn("fetch-depth: 0", workflow)
        self.assertIn(f"uses: loki-inu/relnote@v{__version__}", workflow)
        self.assertIn("--notes-file", workflow)
        self.assertIn("--verify-tag", workflow)
        goreleaser = _block("name: goreleaser")
        self.assertIn("goreleaser/goreleaser-action@v7", goreleaser)
        self.assertIn("args: release --clean --release-notes=notes.md", goreleaser)
        self.assertIn(
            "goreleaser release --clean --release-notes=notes.md",
            "\n".join(_blocks()),
        )


class GoModulePageTests(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        base = Path(self._tmp.name)
        self.repo = base / "repo"
        self.repo.mkdir()
        self.gitconfig = base / "gitconfig"
        self.gitconfig.write_text("", encoding="utf-8")
        _git(["init", "--initial-branch=main"], self.repo)
        _git(["remote", "add", "origin", "https://github.com/you/demo.git"], self.repo)
        (self.repo / "go.mod").write_text(
            _block("module github.com/you/demo\n") + "\n", encoding="utf-8", newline="\n")
        _git(["add", "."], self.repo)
        _git(["commit", "-m", "feat: first release"], self.repo)
        _git(["tag", "-a", "v1.2.0", "-m", "v1.2.0"], self.repo)
        history = _block("git log --oneline").splitlines()[1:]
        for subject in reversed(history):
            _git(["commit", "--allow-empty", "-m", subject], self.repo)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def _env(self) -> dict[str, str]:
        return {
            **os.environ,
            "PYTHONPATH": str(ROOT),
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_CONFIG_GLOBAL": str(self.gitconfig),
            "GIT_AUTHOR_NAME": "Ada Lovelace",
            "GIT_AUTHOR_EMAIL": "ada@example.com",
            "GIT_COMMITTER_NAME": "Ada Lovelace",
            "GIT_COMMITTER_EMAIL": "ada@example.com",
        }

    def _run(self, *argv: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, "-m", "relnote", *argv],
            cwd=self.repo,
            env=self._env(),
            capture_output=True,
            text=True,
            check=False,
        )

    def test_commands_match_the_page(self) -> None:
        nxt = self._run("--next-version")
        self.assertEqual(nxt.returncode, 0, nxt.stderr)
        self.assertEqual(nxt.stdout.strip(), _exact("v1.3.0"))

        _git(["tag", "-a", "v1.3.0", "-m", "v1.3.0"], self.repo)
        ranged = self._run("--since", "v1.2.0", "--until", "v1.3.0")
        self.assertEqual(ranged.returncode, 0, ranged.stderr)
        notes = _block("## What's changed")
        self.assertEqual(_mask(ranged.stdout), _mask(notes))
        self.assertIn("compare/v1.2.0...v1.3.0", ranged.stdout)

        plain = self._run()
        self.assertEqual(plain.returncode, 0, plain.stderr)
        self.assertEqual(_mask(plain.stdout), _mask(notes))

        quiet = self._run("--since", "v1.2.0", "--until", "v1.3.0", "--output", "notes.md", "--quiet")
        self.assertEqual(quiet.returncode, 0, quiet.stderr)
        self.assertEqual(quiet.stdout, "")
        written = (self.repo / "notes.md").read_text(encoding="utf-8")
        self.assertEqual(_mask(written), _mask(notes))


if __name__ == "__main__":
    unittest.main()
